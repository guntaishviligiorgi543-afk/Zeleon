create schema if not exists private;

create table if not exists public.staff_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('manager', 'admin', 'support')),
  status text not null default 'active' check (status in ('active', 'suspended', 'on_leave')),
  appointed_by uuid references auth.users(id) on delete set null,
  appointed_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.staff_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists private.staff_access_grants (
  session_id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  authenticated_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz null,
  created_at timestamptz not null default now()
);

create index if not exists staff_roles_role_status_idx
  on public.staff_roles (role, status);
create index if not exists staff_roles_appointed_by_idx
  on public.staff_roles (appointed_by);
create index if not exists staff_audit_logs_actor_idx
  on public.staff_audit_logs (actor_user_id, created_at desc);
create index if not exists staff_audit_logs_target_idx
  on public.staff_audit_logs (target_user_id, created_at desc);
create index if not exists staff_audit_logs_created_at_idx
  on public.staff_audit_logs (created_at desc);
create index if not exists staff_access_grants_user_expiry_idx
  on private.staff_access_grants (user_id, expires_at)
  where revoked_at is null;

alter table public.staff_roles enable row level security;
alter table public.staff_audit_logs enable row level security;
alter table private.staff_access_grants enable row level security;

revoke all on public.staff_roles from anon, authenticated;
revoke all on public.staff_audit_logs from anon, authenticated;
revoke all on private.staff_access_grants from anon, authenticated;
grant select on public.staff_roles to authenticated;

drop policy if exists staff_roles_read_self on public.staff_roles;
create policy staff_roles_read_self
  on public.staff_roles for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists staff_audit_logs_manager_read on public.staff_audit_logs;
create policy staff_audit_logs_manager_read
  on public.staff_audit_logs for select to authenticated
  using (private.has_staff_access(array['manager']::text[]));

create or replace function private.has_staff_access(allowed_roles text[] default null)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.staff_roles sr
     where sr.user_id = (select auth.uid())
       and sr.status = 'active'
       and sr.role = any(coalesce(allowed_roles, array['manager', 'admin', 'support']::text[]))
       and (select auth.jwt() ->> 'aal') = 'aal2'
  );
$$;

revoke all on function private.has_staff_access(text[]) from public, anon, authenticated;
grant execute on function private.has_staff_access(text[]) to authenticated;

create or replace function public.staff_manage(
  p_actor_user_id uuid,
  p_action text,
  p_target_user_id uuid,
  p_role text default null,
  p_status text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_role text;
  target_role text;
  existing_target_role text;
begin
  select role into actor_role
    from public.staff_roles
   where user_id = p_actor_user_id
     and status = 'active';
  if actor_role is null then raise exception 'Active staff access is required'; end if;
  if p_target_user_id = p_actor_user_id then raise exception 'A staff member cannot modify their own role'; end if;

  select role into existing_target_role from public.staff_roles where user_id = p_target_user_id;
  if existing_target_role = 'manager' then
    raise exception 'The initial manager cannot be modified through ordinary staff management';
  end if;
  target_role := coalesce(p_role, existing_target_role);
  if target_role is null or target_role not in ('admin', 'support') then
    raise exception 'Managers cannot be assigned through ordinary staff management';
  end if;
  if target_role = 'admin' and actor_role <> 'manager' then
    raise exception 'Only a manager can manage admins';
  end if;
  if target_role = 'support' and actor_role not in ('manager', 'admin') then
    raise exception 'Only a manager or admin can manage supports';
  end if;

  if p_action = 'assign' then
    insert into public.staff_roles (user_id, role, status, appointed_by, appointed_at, updated_at)
    values (p_target_user_id, target_role, 'active', p_actor_user_id, now(), now())
    on conflict (user_id) do update
      set role = excluded.role, status = 'active', appointed_by = excluded.appointed_by,
          appointed_at = excluded.appointed_at, updated_at = excluded.updated_at;
  elsif p_action = 'remove' then
    delete from public.staff_roles where user_id = p_target_user_id;
    if not found then raise exception 'Staff assignment was not found'; end if;
  elsif p_action = 'set_status' and p_status in ('active', 'suspended', 'on_leave') then
    update public.staff_roles set status = p_status, updated_at = now()
     where user_id = p_target_user_id;
    if not found then raise exception 'Staff assignment was not found'; end if;
  else
    raise exception 'Invalid staff action';
  end if;

  insert into public.staff_audit_logs (actor_user_id, target_user_id, action, details)
  values (
    p_actor_user_id,
    p_target_user_id,
    case when p_action = 'assign' then 'role_assigned'
         when p_action = 'remove' then 'role_removed'
         when p_status = 'active' then 'staff_reactivated'
         else 'staff_status_changed' end,
    jsonb_build_object('role', target_role, 'status', p_status)
  );
  return jsonb_build_object('ok', true);
end;
$$;

revoke all on function public.staff_manage(uuid, text, uuid, text, text) from public, anon, authenticated;
grant execute on function public.staff_manage(uuid, text, uuid, text, text) to service_role;

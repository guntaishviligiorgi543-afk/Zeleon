async function login(n,aal='aal2',session=n+100) {
  await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:id(n),session_id:id(session),aal,amr:[{method:'password',timestamp:Math.floor(Date.now()/1000)},{method:'totp',timestamp:Math.floor(Date.now()/1000)}]})]);
}
async function allowed(roles=null) { return (await db.query('select private.has_staff_access($1::text[]) as ok',[roles])).rows[0].ok; }
async function manage(action,target,role=null,status=null) { return db.query('select public.staff_manage($1,$2,$3,$4)',[action,id(target),role,status]); }
let passed=0;
async function test(name,fn) {
  await db.exec('begin');
  try { await fn(); passed++; console.log(`PASS ${name}`); }
  finally { await db.exec('rollback'); }
}
